// Pure rules for the AI-generated checklist review stage (20261114000102).

export type TemplateReviewState = "not_ai" | "draft" | "confirmed";

export function templateReviewState(t: { ai_generated?: boolean | null; ai_confirmed_at?: string | null }): TemplateReviewState {
  if (!t.ai_generated) return "not_ai";
  return t.ai_confirmed_at ? "confirmed" : "draft";
}

/** An inspection may start only from a template that is not an unconfirmed AI draft. */
export function canStartFromTemplate(t: { ai_generated?: boolean | null; ai_confirmed_at?: string | null }): boolean {
  return templateReviewState(t) !== "draft";
}

export const AI_DRAFT_START_BLOCK_MESSAGE =
  "This checklist was generated by AI and has not been confirmed yet. JAGS staff must review its items and confirm it before an inspection can start.";

export interface GenerationOutcome {
  /** Activities that received an AI-drafted checklist (saved as drafts awaiting confirmation). */
  drafted: number;
  /** Activities with no checklist because AI was unavailable or returned nothing usable. */
  failed: number;
  /** Why AI was not used, when it was not (gate refusal, provider error). */
  reason: string | null;
}

/** Honest, user-facing summary of a generation run. Never claims a placeholder checklist was made. */
export function describeGeneration(o: GenerationOutcome): { tone: "ok" | "warning"; message: string } {
  if (o.failed === 0 && o.drafted > 0) {
    return { tone: "ok", message: `${o.drafted} AI-generated checklist(s) saved as drafts. Review each one and confirm it before inspections can start.` };
  }
  if (o.failed > 0) {
    const drafted = o.drafted > 0 ? `${o.drafted} AI-generated draft(s) were saved for review. ` : "";
    return {
      tone: "warning",
      message: `${drafted}AI could not draft a checklist for ${o.failed} activity(ies)${o.reason ? ` (${o.reason})` : ""}. No checklist was created for them - create a blank checklist explicitly if you want to write the items yourself.`,
    };
  }
  return { tone: "ok", message: "Nothing to generate." };
}
