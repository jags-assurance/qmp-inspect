/**
 * Guard coverage check. OFFLINE: reads supabase/migrations and the test sources, never touches a
 * database or the network, needs no environment. Safe to run anywhere, including CI (`pnpm test:coverage`).
 *
 * Fails (exit 1) when:
 *   - a database write guard exists in the migrations (trigger function, unique index, table with a
 *     write policy; see migration-scan.ts) but has no entry in guard-registry.ts
 *     -> a NEW guard without a test (or without a conscious "gap" entry) cannot slip in unnoticed
 *   - a registry entry no longer matches anything in the migrations (stale)
 *   - an entry marked `covered` has no `guard("<name>")` in write-guards.test.ts
 *   - an entry marked `covered-existing` points at a guards.test.ts section that does not exist
 *   - a gap / not-a-guard entry has no explanation
 *   - GUARD_COVERAGE.md is out of date (regenerate with `pnpm test:coverage -- --write`)
 *
 * Gaps do NOT fail the check: they are listed, with the reason, in GUARD_COVERAGE.md.
 */
import fs from "node:fs";
import path from "node:path";
import { GUARD_REGISTRY, type GuardEntry } from "./guard-registry";
import { FIRST_MIGRATION, scanGuards, type GuardKind } from "./migration-scan";

const SRC = __dirname;
const DOC_PATH = path.resolve(SRC, "../GUARD_COVERAGE.md");

const KIND_LABEL: Record<GuardKind, string> = {
  trigger_fn: "Trigger function",
  unique_index: "Unique index",
  policy_table: "Table with write policies",
};

export function coverageProblems(): { problems: string[]; entries: (GuardEntry & { migrations: string[] })[] } {
  const problems: string[] = [];
  const found = scanGuards();
  const key = (kind: GuardKind, name: string) => `${kind}:${name}`;
  const registry = new Map(GUARD_REGISTRY.map((e) => [key(e.kind, e.name), e]));
  if (registry.size !== GUARD_REGISTRY.length) problems.push("guard-registry.ts has a duplicate entry");

  for (const f of found) {
    if (!registry.has(key(f.kind, f.name))) {
      problems.push(
        `UNREGISTERED ${KIND_LABEL[f.kind].toLowerCase()} "${f.name}" (${f.migrations.join(", ")}): add it to guard-registry.ts with a live test, or record the gap and why`
      );
    }
  }
  const foundKeys = new Set(found.map((f) => key(f.kind, f.name)));
  for (const e of GUARD_REGISTRY) {
    if (!foundKeys.has(key(e.kind, e.name))) problems.push(`STALE registry entry ${e.kind} "${e.name}": no such guard in migrations from ${FIRST_MIGRATION} onward`);
  }

  const writeGuards = fs.readFileSync(path.join(SRC, "write-guards.test.ts"), "utf8");
  const existing = fs.readFileSync(path.join(SRC, "guards.test.ts"), "utf8");
  for (const e of GUARD_REGISTRY) {
    if (e.status === "covered" && !new RegExp(`guard\\([^)]*"${e.name}"`).test(writeGuards)) {
      problems.push(`"${e.name}" is marked covered by ${e.where} but write-guards.test.ts has no guard(w, ..., "${e.name}", ...)`);
    }
    if (e.status === "covered-existing") {
      const m = /guards\.test\.ts section (\d+)/.exec(e.where);
      if (!m) problems.push(`"${e.name}": covered-existing must say "guards.test.ts section N" (got "${e.where}")`);
      else if (!new RegExp(`section\\("${m[1]}\\. `).test(existing)) problems.push(`"${e.name}": guards.test.ts has no section ${m[1]}`);
    }
    if ((e.status === "gap" || e.status === "not-a-guard") && !(e.note ?? "").trim()) problems.push(`"${e.name}": ${e.status} needs a note saying why`);
  }

  const entries = GUARD_REGISTRY.map((e) => ({ ...e, migrations: found.find((f) => f.kind === e.kind && f.name === e.name)?.migrations ?? [] }));
  return { problems, entries };
}

export function renderCoverageDoc(entries: (GuardEntry & { migrations: string[] })[]): string {
  const count = (s: GuardEntry["status"]) => entries.filter((e) => e.status === s).length;
  const lines: string[] = [];
  lines.push("# Database write-guard coverage");
  lines.push("");
  lines.push("<!-- Generated by `pnpm --filter @jags/rls-tests test:coverage -- --write`. Do not edit by hand; coverage.test.ts fails when it is stale. -->");
  lines.push("");
  lines.push(
    `Every database write guard in \`supabase/migrations\` from \`${FIRST_MIGRATION}\` onward, and the live test that proves it. ` +
      "A guard that is added without an entry in `src/guard-registry.ts` fails `pnpm test:coverage` (offline, no database needed)."
  );
  lines.push("");
  lines.push(
    `**${entries.length} guards**: ${count("covered")} covered by the new write suite (\`src/write-guards.test.ts\`, wrong-role refused + right-role allowed), ` +
      `${count("covered-existing")} covered by the older suites, ${count("not-a-guard")} bookkeeping triggers that refuse nothing, **${count("gap")} gaps** (listed below with the reason).`
  );
  lines.push("");
  lines.push("The live suites WRITE to a real Supabase project and are never part of the default `pnpm test`; see `src/gate.ts` for the two flags they need.");
  lines.push("");
  for (const kind of ["trigger_fn", "unique_index", "policy_table"] as GuardKind[]) {
    lines.push(`## ${KIND_LABEL[kind]}s`);
    lines.push("");
    lines.push("| Guard | Status | Test | Rule | Migration |");
    lines.push("|---|---|---|---|---|");
    for (const e of entries.filter((x) => x.kind === kind)) {
      const status = { covered: "covered", "covered-existing": "covered (older suite)", "not-a-guard": "not a guard", gap: "**GAP**" }[e.status];
      const where = e.status === "covered" ? `write-guards.test.ts ${e.where}` : e.where;
      const rule = e.note ? `${e.rule}. _${e.note}_` : e.rule;
      lines.push(`| \`${e.name}\` | ${status} | ${where} | ${rule.replace(/\|/g, "/")} | ${e.migrations.map((m) => m.split("_")[0]).join(", ")} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

function main(): void {
  const { problems, entries } = coverageProblems();
  const doc = renderCoverageDoc(entries);
  if (process.argv.includes("--write")) {
    fs.writeFileSync(DOC_PATH, doc);
    console.log(`[rls-tests] wrote ${path.relative(process.cwd(), DOC_PATH)}`);
  } else if (!fs.existsSync(DOC_PATH) || fs.readFileSync(DOC_PATH, "utf8") !== doc) {
    problems.push("GUARD_COVERAGE.md is missing or out of date: run `pnpm --filter @jags/rls-tests test:coverage -- --write`");
  }

  const gaps = entries.filter((e) => e.status === "gap");
  console.log(
    `[rls-tests] guard coverage: ${entries.length} guards; ${entries.filter((e) => e.status === "covered").length} covered (write suite), ` +
      `${entries.filter((e) => e.status === "covered-existing").length} covered (older suites), ${entries.filter((e) => e.status === "not-a-guard").length} not-a-guard, ${gaps.length} gaps`
  );
  for (const g of gaps) console.log(`  GAP  ${g.kind} ${g.name} - ${g.note}`);
  if (problems.length > 0) {
    console.error(`\n[rls-tests] ${problems.length} coverage problem(s):`);
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  console.log("[rls-tests] every guard in the migrations is accounted for.");
}

// Only run when executed directly (so another file can import the helpers without side effects).
if (require.main === module) main();
